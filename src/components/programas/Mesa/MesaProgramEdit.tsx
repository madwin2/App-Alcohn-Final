import { useEffect, useState } from 'react';
import { Loader2, Wand2 } from 'lucide-react';
import { Button } from '@/components/ui/button';
import { Dialog, DialogContent, DialogDescription, DialogFooter, DialogHeader, DialogTitle } from '@/components/ui/dialog';
import { Input } from '@/components/ui/input';
import { Label } from '@/components/ui/label';
import { generateProgramName, isAutoGeneratedProgramName } from '@/lib/programas/programName';
import type { PreparationMachine } from '@/lib/programas/preparation';

export interface ProgramEditTarget {
  id: string;
  name: string;
  /** 'YYYY-MM-DD' */
  productionDate: string;
  machine: PreparationMachine;
  stampCount: number;
  /** Ya fue a Aspire: cambiar la fecha lo devuelve a Borrador. */
  inAspire: boolean;
}

/**
 * Nombre y fecha de fabricación de un programa. Mientras el nombre sea el
 * automático («20 OCT x7 C») se sigue actualizando solo con la fecha y la
 * cantidad de sellos; si se escribe otro, queda fijo (BR-PROG-005).
 */
export function MesaProgramEdit({ target, onOpenChange, onSave }: {
  target: ProgramEditTarget | null;
  onOpenChange: (open: boolean) => void;
  onSave: (id: string, updates: { name?: string; productionDate?: string }) => Promise<void>;
}) {
  const [name, setName] = useState('');
  const [date, setDate] = useState('');
  const [saving, setSaving] = useState(false);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    if (!target) return;
    setName(target.name); setDate(target.productionDate); setError(null); setSaving(false);
  }, [target]);

  if (!target) return null;
  const auto = (d: string) => generateProgramName({ date: d, machine: target.machine, stampCount: target.stampCount });
  const wasAuto = isAutoGeneratedProgramName(target.name);
  // Si el nombre seguía siendo el automático, se acompaña el cambio de fecha.
  const shownName = wasAuto && name === target.name && date !== target.productionDate ? auto(date) : name;
  const trimmed = shownName.trim();
  const dateChanged = !!date && date !== target.productionDate;
  const nameChanged = trimmed !== target.name;

  const save = async () => {
    if (!trimmed) { setError('El programa necesita un nombre.'); return; }
    if (!date) { setError('Elegí la fecha de fabricación.'); return; }
    setSaving(true); setError(null);
    try {
      await onSave(target.id, {
        ...(dateChanged ? { productionDate: date } : {}),
        // El automático lo recalcula el servidor con la fecha nueva; solo se manda un nombre escrito a mano.
        ...(nameChanged && !(isAutoGeneratedProgramName(trimmed) && trimmed === auto(date) && dateChanged) ? { name: trimmed } : {}),
      });
      onOpenChange(false);
    } catch (e) {
      setError(e instanceof Error ? e.message : 'No se pudo guardar');
    } finally { setSaving(false); }
  };

  return (
    <Dialog open onOpenChange={(o) => { if (!saving) onOpenChange(o); }}>
      <DialogContent className="sm:max-w-[420px]">
        <DialogHeader>
          <DialogTitle>Nombre y fecha</DialogTitle>
          <DialogDescription>El nombre automático se actualiza solo con la fecha y la cantidad de sellos. Si escribís otro, queda fijo.</DialogDescription>
        </DialogHeader>
        <form className="space-y-4" onSubmit={(e) => { e.preventDefault(); void save(); }}>
          <div className="space-y-1.5">
            <Label htmlFor="mesa-programa-nombre">Nombre</Label>
            <div className="flex gap-2">
              <Input id="mesa-programa-nombre" value={shownName} autoFocus maxLength={60}
                onChange={(e) => setName(e.target.value)} />
              <Button type="button" variant="outline" size="icon" title="Usar el nombre automático" aria-label="Usar el nombre automático"
                onClick={() => setName(auto(date || target.productionDate))}>
                <Wand2 className="size-4" />
              </Button>
            </div>
          </div>
          <div className="space-y-1.5">
            <Label htmlFor="mesa-programa-fecha">Fecha de fabricación</Label>
            <Input id="mesa-programa-fecha" type="date" value={date} onChange={(e) => setDate(e.target.value)} className="[color-scheme:dark]" />
            {dateChanged && target.inAspire ? (
              <p className="text-[12px] text-amber-200/90">Ya estaba en Aspire: al cambiar la fecha vuelve a Borrador y hay que correr el gadget de nuevo.</p>
            ) : null}
          </div>
          {error ? <p className="text-[13px] text-red-300" role="alert">{error}</p> : null}
          <DialogFooter>
            <Button type="button" variant="ghost" disabled={saving} onClick={() => onOpenChange(false)}>Cancelar</Button>
            <Button type="submit" disabled={saving || (!dateChanged && !nameChanged)}>
              {saving ? <Loader2 className="mr-2 size-4 animate-spin" /> : null}Guardar
            </Button>
          </DialogFooter>
        </form>
      </DialogContent>
    </Dialog>
  );
}
